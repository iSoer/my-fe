import { z } from "zod"
import { infiniteRequest, infiniteResponse } from "../pagination"

// Contract of the pokemon generator (src/server/pokemon-model, docs/pokemon-model.md)

export const POKEMON_TYPES = [
  "normal", "fire", "water", "electric", "grass", "ice", "fighting", "poison", "ground",
  "flying", "psychic", "bug", "rock", "ghost", "dragon", "dark", "steel", "fairy"
] as const

export const STATS = ["hp", "attack", "defense", "specialAttack", "specialDefense", "speed"] as const

export const POKEMON_CLASSES = ["stage", "single", "semiLegendary", "pseudoLegendary", "legendary"] as const

export const ARCHETYPES = ["physical", "special", "tank", "fast", "hpWall", "balanced"] as const

export const POKEMON_FORMS = ["mega"] as const

export const MAX_SEED = 2 ** 32 - 1

export type PokemonType = typeof POKEMON_TYPES[number]

export type Stat = typeof STATS[number]

export type PokemonClass = typeof POKEMON_CLASSES[number]

export type Archetype = typeof ARCHETYPES[number]

const distinct = (items: unknown[]) => new Set(items).size === items.length

export const pokemonTypeSchema = z.enum(POKEMON_TYPES)

export const pokemonNameSchema = z.string().min(1).max(40).regex(/^[a-z0-9-]+$/, { error: "Only a-z, 0-9 and -" })

export const seedSchema = z.number().int().min(0).max(MAX_SEED)

const abilityName = z.string().min(1).max(64).regex(/^[a-z0-9-]+$/, { error: "Only a-z, 0-9 and -" })

const typesField = z.array(pokemonTypeSchema).min(1).max(2).refine(distinct, { error: "Types must be different" })

const abilitiesField = z.array(abilityName).min(1).max(3).refine(distinct, { error: "Abilities must be different" })

export const stageSchema = z.object({
  index: z.number().int().min(1).max(3),
  of: z.number().int().min(2).max(3)
}).refine(stage => stage.index <= stage.of, { error: "stage.index must not exceed stage.of" })

export const statsSchema = z.object({
  hp: z.number().int(),
  attack: z.number().int(),
  defense: z.number().int(),
  specialAttack: z.number().int(),
  specialDefense: z.number().int(),
  speed: z.number().int()
})

/** Everything is optional: what is not given is generated by the model */
export const generateRequestSchema = z.object({
  class: z.enum(POKEMON_CLASSES).optional(),
  stage: stageSchema.optional(),
  types: typesField.optional(),
  archetype: z.enum(ARCHETYPES).optional(),
  bst: z.number().int().min(175).max(720).optional(),
  abilities: abilitiesField.optional(),
  name: pokemonNameSchema.optional()
})

export const generateLineRequestSchema = z.object({
  length: z.union([z.literal(2), z.literal(3)]),
  types: typesField.optional(),
  archetype: z.enum(ARCHETYPES).optional(),
  abilities: abilitiesField.optional()
})

/** Stats distributed by hand (the /generate page); the server adds size, experience and archetype */
export const customPokemonSchema = z.object({
  name: pokemonNameSchema.optional(),
  class: z.enum(POKEMON_CLASSES),
  stage: stageSchema.optional(),
  types: typesField,
  abilities: abilitiesField,
  stats: statsSchema,
  archetype: z.enum(ARCHETYPES).optional()
})

/** What a pokemon was generated from; stored in generated_pokemon.request to reproduce it */
export const generationInputSchema = z.discriminatedUnion("mode", [
  z.object({ mode: z.literal("single"), request: generateRequestSchema }),
  z.object({ mode: z.literal("line"), request: generateLineRequestSchema }),
  z.object({ mode: z.literal("custom"), pokemon: customPokemonSchema }),
  // baseId is the saved base pokemon; absent when the mega form is built from an unsaved one
  z.object({ mode: z.literal("mega"), baseId: z.uuid().optional() })
])

/** Body of POST /api/pokemon/generated and /preview; `mode` defaults to "single", `request` to {} */
export const generateBodySchema = z.preprocess(
  (value) => {
    if (typeof value !== "object" || value === null || Array.isArray(value)) {
      return value
    }

    const body = { mode: "single", ...value } as Record<string, unknown>

    return body.mode === "single" && body.request === undefined ? { ...body, request: {} } : body
  },
  z.discriminatedUnion("mode", [
    z.object({ mode: z.literal("single"), request: generateRequestSchema, seed: seedSchema.optional() }),
    z.object({ mode: z.literal("line"), request: generateLineRequestSchema, seed: seedSchema.optional() }),
    z.object({ mode: z.literal("mega"), baseId: z.uuid(), seed: seedSchema.optional() }),
    z.object({ mode: z.literal("custom"), pokemon: customPokemonSchema, seed: seedSchema.optional() })
  ])
)

export const generatedPokemonItem = z.object({
  name: pokemonNameSchema,
  types: z.array(pokemonTypeSchema).min(1).max(2),
  abilities: z.array(z.string()).min(1).max(3),
  heightDm: z.number().int(),
  weightHg: z.number().int(),
  baseExperience: z.number().int(),
  stats: statsSchema,
  class: z.enum(POKEMON_CLASSES),
  stage: stageSchema.nullable(),
  archetype: z.enum(ARCHETYPES),
  form: z.enum(POKEMON_FORMS).nullable(),
  seed: seedSchema,
  modelVersion: z.number().int(),
  input: generationInputSchema,
  // Decisions the generator made; only in generation responses, not stored
  explain: z.array(z.string()).optional()
})

export const savedGeneratedPokemonItem = generatedPokemonItem.extend({
  id: z.uuid(),
  // Previous evolution stage, or the base pokemon of a form
  parentId: z.uuid().nullable()
})

export const generatePreviewResponseSchema = z.object({
  data: z.array(generatedPokemonItem)
})

export const generateSaveResponseSchema = z.object({
  data: z.array(savedGeneratedPokemonItem)
})

/** `?types=fire&types=flying`: empty values dropped, duplicates removed, AND semantics */
const typesParam = z.preprocess(
  value => (value === undefined || value === null ? [] : Array.isArray(value) ? value : [value]),
  z
    .array(z.string())
    .transform(types => [...new Set(types.filter(type => type !== ""))])
    .pipe(z.array(pokemonTypeSchema).max(2))
)

export const generatedListRequestSchema = z.object({
  types: typesParam,
  class: z.enum(POKEMON_CLASSES).optional(),
  // asc: oldest first (default), desc: newest first
  order: z.enum(["asc", "desc"]).default("asc")
}).extend(infiniteRequest.shape)

export const generatedListResponseSchema = z.object({
  data: z.array(savedGeneratedPokemonItem),
  pagination: infiniteResponse
})

export const generatedItemResponseSchema = z.object({
  data: savedGeneratedPokemonItem
})

const statNumbers = z.object({
  hp: z.number(),
  attack: z.number(),
  defense: z.number(),
  specialAttack: z.number(),
  specialDefense: z.number(),
  speed: z.number()
})

const partialStats = z.partialRecord(z.enum(STATS), z.number())

/** GET /api/pokemon/generated/model: the parts of the model the /generate page builds its limits from */
export const generatorModelResponseSchema = z.object({
  data: z.object({
    version: z.number().int(),
    forbiddenBst: z.array(z.tuple([z.number().int(), z.number().int()])),
    profileMean: statNumbers,
    // In CLASS_KEYS order; classes without real pokemon are left out
    classes: z.array(z.object({
      key: z.string(),
      class: z.enum(POKEMON_CLASSES),
      stage: stageSchema.nullable(),
      count: z.number().int(),
      bst: z.object({ min: z.number(), max: z.number(), mean: z.number() }),
      stat: z.object({ min: z.number(), max: z.number() }),
      // P(1 ability), P(2), P(3)
      abilityCount: z.tuple([z.number(), z.number(), z.number()])
    })),
    types: z.record(pokemonTypeSchema, z.object({ profileShift: statNumbers, bstShift: z.number() })),
    abilities: z.array(z.object({
      name: z.string(),
      count: z.number().int(),
      types: z.partialRecord(pokemonTypeSchema, z.number().int()),
      shift: statNumbers.nullable(),
      universal: z.boolean(),
      meanBst: z.number(),
      // Form-change mechanics; the generator never picks them
      formOnly: z.boolean()
    })),
    // Abilities that bend the stat budget (src/server/pokemon-model/compensation.ts)
    compensation: z.record(z.string(), z.object({
      maxShare: partialStats.optional(),
      fixedStats: partialStats.optional(),
      equalStats: z.boolean().optional(),
      bstFactor: z.number().optional(),
      // In-battle multipliers, for display only
      statMultiplier: partialStats.optional(),
      note: z.string()
    }))
  })
})

export type GenerateRequestType = z.infer<typeof generateRequestSchema>

export type CustomPokemonType = z.infer<typeof customPokemonSchema>

export type GeneratorModelType = z.infer<typeof generatorModelResponseSchema>["data"]

export type GenerateLineRequestType = z.infer<typeof generateLineRequestSchema>

export type GenerationInputType = z.infer<typeof generationInputSchema>

export type GenerateBodyType = z.infer<typeof generateBodySchema>

export type GeneratedPokemonType = z.infer<typeof generatedPokemonItem>

export type SavedGeneratedPokemonType = z.infer<typeof savedGeneratedPokemonItem>

export type GeneratedListRequestType = z.infer<typeof generatedListRequestSchema>
